"""Embed the web UI into the firmware (offline dev tool, nothing here runs on the arm).

Gzips web/index.html (the page) and web/arm.bin (the arm's meshes, made by tools/build_arm_mesh.py) and writes
src/main/web_assets.h, which the ESP32 build and the PC simulator compile in. PlatformIO runs this
automatically before every `pio run -e main` (tools/pio_build_web.py), so editing web/index.html and building
is enough. Run it by hand with `python tools/build_web.py [--force]`.
"""
import gzip
import os
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = [("index.html", "kIndex"), ("arm.bin", "kArm")]      # web/<file> -> <prefix>Gz, <prefix>GzLen, <prefix>Etag


def build(force=False, root=ROOT):
    srcs = [os.path.join(root, "web", f) for f, _ in FILES]
    out = os.path.join(root, "src", "main", "web_assets.h")
    if not force and os.path.exists(out) and all(os.path.getmtime(out) >= os.path.getmtime(s) for s in srcs):
        return False
    lines = [
        "// GENERATED by tools/build_web.py from web/ - do not edit. Include it in one .cpp per program.",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "namespace raft {",
        "namespace webui {",
    ]
    for (name, prefix), src in zip(FILES, srcs):
        raw = open(src, "rb").read()
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        etag = "%08x" % (zlib.crc32(raw) & 0xFFFFFFFF)
        lines += [
            "",
            "// web/%s: %d bytes, %d gzipped" % (name, len(raw), len(gz)),
            'static const char %sEtag[] = "\\"%s\\"";' % (prefix, etag),
            "static const size_t %sRawLen = %d;" % (prefix, len(raw)),
            "static const size_t %sGzLen = %d;" % (prefix, len(gz)),
            "static const uint8_t %sGz[] = {" % prefix,
        ]
        for i in range(0, len(gz), 20):
            lines.append("    " + ", ".join("0x%02x" % b for b in gz[i:i + 20]) + ",")
        lines.append("};")
    lines += ["", "}  // namespace webui", "}  // namespace raft", ""]
    with open(out, "w", newline="\n") as fh:
        fh.write("\n".join(lines))
    return True


if __name__ == "__main__":
    changed = build(force="--force" in sys.argv)
    print(("wrote" if changed else "up to date:"), os.path.join("src", "main", "web_assets.h"),
          "(" + ", ".join("%s %d bytes" % (f, os.path.getsize(os.path.join(ROOT, "web", f))) for f, _ in FILES) + ")")
